export function exportScriptToJson(skit: SkitTemplate): string {
  return JSON.stringify(skit, null, 2);
}

export function importScriptFromJson(jsonStr: string): { skit?: SkitTemplate; error?: string } {
  try {
    const parsed = JSON.parse(jsonStr) as SkitTemplate;
    const validation = validateScript(parsed);
    if (!validation.valid) {
      return { error: `Invalid script format: ${validation.errors.join(', ')}` };
    }
    return { skit: parsed };
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Unknown JSON parse error';
    return { error: `Malformed JSON: ${message}` };
  }
}
